#!/usr/bin/env python3
"""Generate the MXCSR FTZ|DAZ twin of every lifted SPU module (SPU codegen v3).

The shipped game build carries two variants of each lifted module:

  * the base module (`<SPU_DIR>/<name>/spu_recomp.c`), registered as variant 0
    and exactly the code the title has always run;
  * a twin in `<SPU_DIR>/<name>_ftz/`, identical control flow and native hooks
    but with the six SPU float helpers (`fa/fs/fm/fma/fms/fnms`) replaced by the
    hardware `spu_hw_*` forms that rely on the host thread running with MXCSR
    FTZ|DAZ.

`PS3RECOMP_SPU_FTZ` (live key, default 0) is sampled once per lifted run; the
runtime sets MXCSR for the run and dispatch prefers the variant-1 functions.
When the key is off the base module runs unchanged, so a build tree without the
variant registry (the play tree) is inert: the twin's registration calls a
weak `spu_register_function_var`, sees it absent, and registers nothing.

The twin is derived from the already-generated, already-patched base source, so
it inherits the cull/native/Pm patches byte for byte; only the float helper
selection differs. Everything this script writes is regenerated from the base
on every run, so it is idempotent and can be re-run after any relift.

The default shape is v3 (each float helper canonicalises its result), and it is
regenerated byte for byte. `--lazy-zero` is the v4 experiment: raw helpers plus
a dataflow pass that canonicalises the sign of zero only where a value is
observed. It is exact but measured neutral (see the v4 section of
docs/spu-codegen-v2.md in the game port), so it is not the default.

`--approx` writes the variant-2 twins (`<name>_approx/`, PS3RECOMP_SPU_FLOAT_APPROX)
instead, also from the base module: native float ops with no sign-of-zero
canonicalisation, and full-precision frest/frsqest/fi. It is NOT bit-exact and is
default off; the ftz output is unaffected by this mode.

Usage:
  tools/spu_ftz_twin.py --spu-dir recomp-work/spu_lifted [--lazy-zero|--approx] [--remove]
"""
import argparse
import os
import re
import sys

FTZ_PREAMBLE = r"""
/* PS3RECOMP_SPU_FTZ twin: SPU float on a host thread running MXCSR FTZ|DAZ.
 * SPU has no denormals and every zero result is +0, so the hardware can flush
 * denormal operands/results and only the sign of zero is canonicalised. */
#if defined(__FMA__) && (defined(__SSE__) || defined(__AVX__))
#include <immintrin.h>
static inline __m128 spu_hw_ftz(__m128 v) {
    return _mm_andnot_ps(_mm_cmpeq_ps(v, _mm_setzero_ps()), v);
}
static inline __m128 spu_hw_ld(u128 a) { return _mm_loadu_ps((const float*)a._u32); }
static inline u128 spu_hw_st(__m128 v) {
    u128 r; _mm_storeu_ps((float*)r._u32, spu_hw_ftz(v)); return r;
}
static inline u128 spu_hw_fa(u128 a, u128 b) { return spu_hw_st(_mm_add_ps(spu_hw_ld(a), spu_hw_ld(b))); }
static inline u128 spu_hw_fs(u128 a, u128 b) { return spu_hw_st(_mm_sub_ps(spu_hw_ld(a), spu_hw_ld(b))); }
static inline u128 spu_hw_fm(u128 a, u128 b) { return spu_hw_st(_mm_mul_ps(spu_hw_ld(a), spu_hw_ld(b))); }
static inline u128 spu_hw_fma(u128 a, u128 b, u128 c)  { return spu_hw_st(_mm_fmadd_ps(spu_hw_ld(a), spu_hw_ld(b), spu_hw_ld(c))); }
static inline u128 spu_hw_fms(u128 a, u128 b, u128 c)  { return spu_hw_st(_mm_fmsub_ps(spu_hw_ld(a), spu_hw_ld(b), spu_hw_ld(c))); }
static inline u128 spu_hw_fnms(u128 a, u128 b, u128 c) { return spu_hw_st(_mm_fnmadd_ps(spu_hw_ld(a), spu_hw_ld(b), spu_hw_ld(c))); }
#else
/* No FMA: fall back to the exact helpers; the twin is then identical. */
#define spu_hw_fa spu_fa
#define spu_hw_fs spu_fs
#define spu_hw_fm spu_fm
#define spu_hw_fma spu_fma
#define spu_hw_fms spu_fms
#define spu_hw_fnms spu_fnms
#endif
extern void spu_register_function_var(uint32_t, void (*)(spu_context*), int)
    __attribute__((weak));
"""

APPROX_PREAMBLE = r"""
/* PS3RECOMP_SPU_FLOAT_APPROX twin: SPU float on a host thread running MXCSR
 * FTZ|DAZ, NOT bit-exact. Float results keep the host sign of zero (SPU zero
 * is +0), frest/frsqest are full-precision (the lifted Newton step after them
 * then converges) and fi passes the estimate through. */
#if defined(__FMA__) && (defined(__SSE__) || defined(__AVX__))
#include <immintrin.h>
static inline __m128 spu_ap_ld(u128 a) { return _mm_loadu_ps((const float*)a._u32); }
static inline u128 spu_ap_st(__m128 v) { u128 r; _mm_storeu_ps((float*)r._u32, v); return r; }
static inline u128 spu_ap_fa(u128 a, u128 b) { return spu_ap_st(_mm_add_ps(spu_ap_ld(a), spu_ap_ld(b))); }
static inline u128 spu_ap_fs(u128 a, u128 b) { return spu_ap_st(_mm_sub_ps(spu_ap_ld(a), spu_ap_ld(b))); }
static inline u128 spu_ap_fm(u128 a, u128 b) { return spu_ap_st(_mm_mul_ps(spu_ap_ld(a), spu_ap_ld(b))); }
static inline u128 spu_ap_fma(u128 a, u128 b, u128 c)  { return spu_ap_st(_mm_fmadd_ps(spu_ap_ld(a), spu_ap_ld(b), spu_ap_ld(c))); }
static inline u128 spu_ap_fms(u128 a, u128 b, u128 c)  { return spu_ap_st(_mm_fmsub_ps(spu_ap_ld(a), spu_ap_ld(b), spu_ap_ld(c))); }
static inline u128 spu_ap_fnms(u128 a, u128 b, u128 c) { return spu_ap_st(_mm_fnmadd_ps(spu_ap_ld(a), spu_ap_ld(b), spu_ap_ld(c))); }
/* A zero input keeps the exact helpers' result (exponent 255, the SPU "huge"
 * sentinel the lifted code compares against); the fi pass-through keeps that
 * lane's estimate with its interpolation bits cleared, as spu_fi does for it. */
static inline __m128 spu_ap_zsel(__m128 x, __m128 v, uint32_t bits, int keep_sign) {
    const __m128 d = _mm_or_ps(_mm_castsi128_ps(_mm_set1_epi32((int)bits)),
                               keep_sign ? _mm_and_ps(x, _mm_set1_ps(-0.0f)) : _mm_setzero_ps());
    return _mm_blendv_ps(v, d, _mm_cmpeq_ps(x, _mm_setzero_ps()));
}
static inline u128 spu_ap_frest(u128 a) {
    const __m128 x = spu_ap_ld(a);
    return spu_ap_st(spu_ap_zsel(x, _mm_div_ps(_mm_set1_ps(1.0f), x),
                                 0x7F800000u | (spu_frest_fraction_lut[0] & 0x7FFFFFu), 1));
}
static inline u128 spu_ap_frsqest(u128 a) {
    const __m128 x = spu_ap_ld(a);
    const __m128 m = _mm_andnot_ps(_mm_set1_ps(-0.0f), x);
    return spu_ap_st(spu_ap_zsel(x, _mm_div_ps(_mm_set1_ps(1.0f), _mm_sqrt_ps(m)),
                                 0x7F800000u | (spu_frsqest_fraction_lut[0] & 0x7FFFFFu), 0));
}
static inline u128 spu_ap_fi(u128 a, u128 b) {
    (void)a;
    const __m128i e = _mm_loadu_si128((const __m128i*)b._u32);
    const __m128i huge = _mm_cmpeq_epi32(_mm_and_si128(_mm_srli_epi32(e, 23), _mm_set1_epi32(0xFF)), _mm_set1_epi32(0xFF));
    u128 r; _mm_storeu_si128((__m128i*)r._u32, _mm_andnot_si128(_mm_and_si128(huge, _mm_set1_epi32(0x3FF)), e));
    return r;
}
/* The base helpers stay defined above; these shadow the names from here on. */
#define spu_frest spu_ap_frest
#define spu_frsqest spu_ap_frsqest
#define spu_fi spu_ap_fi
#else
/* No FMA: fall back to the exact helpers; the twin is then identical. */
#define spu_ap_fa spu_fa
#define spu_ap_fs spu_fs
#define spu_ap_fm spu_fm
#define spu_ap_fma spu_fma
#define spu_ap_fms spu_fms
#define spu_ap_fnms spu_fnms
#endif
extern void spu_register_function_var(uint32_t, void (*)(spu_context*), int)
    __attribute__((weak));
"""

# Opt-in extras for the _approx twin only (flags default off; the default output is unchanged).
# --fast-cfl: cflts/cfltu as one scale multiply + cvttps2dq (+ saturation fixups) instead of the
# integer shift emulation. Bit-exact for every input when the thread runs FTZ|DAZ (checked against
# spu_cflts_ref by tools/spu_cfl_check.c).
APPROX_FAST_CFL = r"""
#if defined(__FMA__) && (defined(__SSE__) || defined(__AVX__))
/* x * 2^(173 - i8) is exact (power of two; FTZ drops only results < 1 that truncate to 0). Out-of-range
 * and Inf/NaN lanes make cvttps2dq return 0x80000000: positive lanes saturate to 0x7FFFFFFF. */
static inline __m128 spu_ap_pow2(int p) { return _mm_castsi128_ps(_mm_set1_epi32((p + 127) << 23)); }   /* p in [-126, 127] */
static inline __m128 spu_ap_cfl_scale(__m128 x, int i8) {
    const int k = 173 - (i8 & 0xFF);
    if (k > 127) return _mm_mul_ps(_mm_mul_ps(x, spu_ap_pow2(k / 2)), spu_ap_pow2(k - k / 2));
    return _mm_mul_ps(x, spu_ap_pow2(k));
}
static inline u128 spu_ap_cflts(u128 a, int i8) {
    const __m128 x = spu_ap_ld(a);
    const __m128i c = _mm_cvttps_epi32(spu_ap_cfl_scale(x, i8));
    const __m128i neg = _mm_srai_epi32(_mm_castps_si128(x), 31);
    const __m128i oor = _mm_cmpeq_epi32(c, _mm_set1_epi32((int)0x80000000u));
    u128 r; _mm_storeu_si128((__m128i*)r._u32, _mm_xor_si128(c, _mm_andnot_si128(neg, oor))); return r;
}
static inline u128 spu_ap_cfltu(u128 a, int i8) {
    const __m128 x = spu_ap_ld(a);
    const __m128 y = spu_ap_cfl_scale(x, i8);
    const __m128i neg = _mm_srai_epi32(_mm_castps_si128(x), 31);
    const __m128i lo = _mm_cvttps_epi32(y);
    const __m128i hi = _mm_xor_si128(_mm_cvttps_epi32(_mm_sub_ps(y, _mm_set1_ps(2147483648.0f))),
                                     _mm_set1_epi32((int)0x80000000u));
    const __m128i big = _mm_castps_si128(_mm_cmpnlt_ps(y, _mm_set1_ps(2147483648.0f)));   /* NaN counts as big */
    const __m128i huge = _mm_castps_si128(_mm_cmpnlt_ps(y, _mm_set1_ps(4294967296.0f)));
    const __m128i v = _mm_or_si128(_mm_blendv_epi8(lo, hi, big), huge);
    u128 r; _mm_storeu_si128((__m128i*)r._u32, _mm_andnot_si128(neg, v)); return r;
}
#undef spu_cflts
#undef spu_cfltu
#define spu_cflts spu_ap_cflts
#define spu_cfltu spu_ap_cfltu
#endif
"""

# --rcp-est (NOT bit-exact): frest/frsqest from rcpps/rsqrtps (12-bit, like the SPU estimate) instead
# of a full-precision divide / sqrt+divide; the lifted Newton step after them still converges.
APPROX_RCP_EST = r"""
#if defined(__FMA__) && (defined(__SSE__) || defined(__AVX__))
static inline u128 spu_ap_frest_rcp(u128 a) {
    const __m128 x = spu_ap_ld(a);
    return spu_ap_st(spu_ap_zsel(x, _mm_rcp_ps(x), 0x7F800000u | (spu_frest_fraction_lut[0] & 0x7FFFFFu), 1));
}
static inline u128 spu_ap_frsqest_rcp(u128 a) {
    const __m128 x = spu_ap_ld(a);
    return spu_ap_st(spu_ap_zsel(x, _mm_rsqrt_ps(_mm_andnot_ps(_mm_set1_ps(-0.0f), x)),
                                 0x7F800000u | (spu_frsqest_fraction_lut[0] & 0x7FFFFFu), 0));
}
#undef spu_frest
#undef spu_frsqest
#define spu_frest spu_ap_frest_rcp
#define spu_frsqest spu_ap_frsqest_rcp
#endif
"""

