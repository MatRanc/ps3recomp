HELPER_RE = re.compile(r"\bspu_(fnms|fma|fms|fa|fs|fm)\s*\(")
ASSIGN_FLOAT_RE = re.compile(
    r"^\s*sr(\d+)\s*=\s*spu_u2v\(spu_(fnms|fma|fms|fa|fs|fm)\s*\(")
RAWDEF_RE = re.compile(
    r"\bsr(\d+)\s*=\s*spu_u2v\(spu_hw_(fnms|fma|fms|fa|fs|fm)_raw\s*\(")
SR_RE = re.compile(r"\bsr(\d+)\b")
DEF_RE = re.compile(r"\bsr(\d+)\s*=")
HW_CALL_RE = re.compile(r"\bspu_hw_(?:fnms|fma|fms|fa|fs|fm)(?:_raw)?\s*\(")
PLAIN_STMT_RE = re.compile(r"^\s*(?:spu_v4u\s+)?sr\d+\s*=")
FUNC_START_RE = re.compile(r"^void\s+\w+_spu_func_[0-9A-Fa-f]+(?:_body)?\s*\(")
BOUNDARY_TOKENS = ("loc_", "goto ", "if (", "return;", "SPU_RET", "SPU_DIRECT",
                   "spu_unsupported", "SPU_STOP", "spu_stop", "for (", "while (",
                   "switch (", "ctx->", "{", "}")
REG_LINE = ("    for (const spu_func_entry* e = spu_function_table; e->func; ++e)\n"
            "        spu_register_function(e->addr, e->func);")

# The twins call the variant registry through a weak declaration, so the play
# tree (no registry) links and registers nothing. Windows cannot use the weak
# form: the registry lives in a static library, and a weak reference with a
# default body keeps lld-link from pulling that member, so the twins' defaults
# collide ("duplicate symbol"). spu_channels.c always defines the registry, so
# Windows takes a plain extern and the reference resolves.
_WEAK_REGISTRY_DECL = ("extern void spu_register_function_var(uint32_t, void (*)(spu_context*), int)\n"
                       "    __attribute__((weak));\n")
_REGISTRY_DECL = ("#if defined(_WIN32)\n"
                  "extern void spu_register_function_var(uint32_t, void (*)(spu_context*), int);\n"
                  "#else\n"
                  + _WEAK_REGISTRY_DECL +
                  "#endif\n")
FTZ_PREAMBLE = FTZ_PREAMBLE.replace(_WEAK_REGISTRY_DECL, _REGISTRY_DECL)
APPROX_PREAMBLE = APPROX_PREAMBLE.replace(_WEAK_REGISTRY_DECL, _REGISTRY_DECL)
FTZ_PREAMBLE_LAZY = FTZ_PREAMBLE_LAZY.replace(_WEAK_REGISTRY_DECL, _REGISTRY_DECL)


def rewrite_helpers(text: str) -> str:
    """Rename the six base float helpers to the hardware forms.

    A statement that is exactly `srN = spu_u2v(spu_op(...));` uses the raw
    result form (the lazy pass decides where to canonicalise). Every other use
    (a direct `ctx->gpr[N] = spu_op(...)`, a store, a nested call) takes the
    canonicalising form, because its result is observed right there.
    """
    out = []
    for line in text.splitlines(keepends=True):
        body = line.rstrip("\n")
        nl = line[len(body):]
        if "spu_" not in body:
            out.append(line)
            continue
        stmts = [p for p in body.split(";") if p.strip()]
        plain = bool(stmts) and all(PLAIN_STMT_RE.match(p) for p in stmts)
        if plain:
            parts = []
            for p in body.split(";"):
                if ASSIGN_FLOAT_RE.match(p):
                    p = HELPER_RE.sub(lambda m: "spu_hw_" + m.group(1) + "_raw(", p, count=1)
                else:
                    p = HELPER_RE.sub(lambda m: "spu_hw_" + m.group(1) + "(", p)
                parts.append(p)
            body = ";".join(parts)
        else:
            body = HELPER_RE.sub(lambda m: "spu_hw_" + m.group(1) + "(", body)
        out.append(body + nl)
    return "".join(out)


def _call_spans(s: str):
    """Character spans of the argument lists of every spu_hw_* call in `s`."""
    spans = []
    for m in HW_CALL_RE.finditer(s):
        depth = 0
        for j in range(m.end() - 1, len(s)):
            if s[j] == "(":
                depth += 1
            elif s[j] == ")":
                depth -= 1
                if depth == 0:
                    spans.append((m.start(), j + 1))
                    break
    return spans


def _line_info(line: str):
    body = line.rstrip("\n")
    s = body.strip()
    if not s or s.startswith("/*") or s.startswith("//"):
        return {"kind": "keep"}
    if any(t in body for t in BOUNDARY_TOKENS) or s.endswith(":"):
        return {"kind": "boundary"}
    spans = _call_spans(body)
    uses = []
    for m in SR_RE.finditer(body):
        if re.match(r"\s*=", body[m.end():]):
            continue                      # definition lhs, not a use
        if not any(a <= m.start() < b for a, b in spans):
            uses.append((int(m.group(1)), m.start()))
    rawdefs = [(int(m.group(1)), m.group(2), m.start(), m.end())
               for m in RAWDEF_RE.finditer(body)]
    defs = {int(m.group(1)) for m in DEF_RE.finditer(body)}
    return {"kind": "code", "uses": uses, "rawdefs": rawdefs, "defs": defs}


def _kept_raw(infos):
    """Which raw definitions are worth keeping deferred.

    A definition is kept raw only when its value is never observed before the
    register is redefined or the block ends. Then the canonicalisation is
    either saved (dead/overwritten value) or paid once on the float result
    that is actually observed. When the value itself is observed, the raw form
    buys nothing and the definition uses the canonicalising helper, which is
    exactly the v3 code shape (no extra round trip).
    """
    kept = {}
    for i, info in enumerate(infos):
        if info["kind"] != "code":
            continue
        for (r, _op, ds, de) in info["rawdefs"]:
            # A deferred value is only a win when it is killed by a later
            # definition before anything observes it. Everything else is
            # canonicalised at the definition (the v3 shape): it is going to
            # be observed (stored / written back / consumed as integer) or it
            # is still live at the block end, where the write-back sees it.
            killed = False
            if not any(ur == r and pos > de for (ur, pos) in info["uses"]):
                for j in range(i + 1, len(infos)):
                    ni = infos[j]
                    if ni["kind"] != "code":
                        break
                    if any(ur == r for (ur, _pos) in ni["uses"]):
                        break
                    if r in ni["defs"]:
                        killed = True
                        break
            kept[(i, r, ds)] = killed
    return kept


def lazy_canonicalize(text: str) -> str:
    """Defer sign-of-zero canonicalisation (v4).

    A register assigned from a raw float helper may stay raw while only SPU
    float ops consume it. Its value is canonicalised where it is observed
    (bitwise/integer consumer, LS store, GPR write-back, call/exit) or at the
    block end if it is still live. Every control-flow boundary is a flush
    point, so no raw value crosses a merge; any shape this pass does not
    understand falls back to the canonicalising helper at the definition.
    """
    out = []
    in_func = False
    body_lines = []

    def emit(infos):
        kept = _kept_raw(infos)
        raw = set()

        def flush(indent, regs):
            for r in sorted(regs):
                out.append("%ssr%d = spu_u2v(spu_hw_c(spu_v2u(sr%d)));\n" % (indent, r, r))
            raw.difference_update(regs)

        for i, info in enumerate(infos):
            line = info["line"]
            if info["kind"] == "keep":
                out.append(line)
                continue
            body = line.rstrip("\n")
            nl = line[len(body):]
            indent = body[:len(body) - len(body.lstrip())]
            if info["kind"] == "boundary":
                flush(indent, set(raw))
                out.append(line)
                continue
            newbody = body
            counts = {}
            for (r, op, ds, _de) in info["rawdefs"]:
                if not kept.get((i, r, ds), False):
                    counts[op] = counts.get(op, 0) + 1
            for op, n in counts.items():
                newbody = newbody.replace("spu_hw_%s_raw(" % op, "spu_hw_%s(" % op, n)
            unsafe = {r for (r, _pos) in info["uses"] if r in raw}
            if unsafe:
                flush(indent, unsafe)
            out.append(newbody + nl)
            for r in info["defs"]:
                raw.discard(r)
            for (r, _op, ds, _de) in info["rawdefs"]:
                if kept.get((i, r, ds), False):
                    raw.add(r)
        flush("", set(raw))

    for line in text.splitlines(keepends=True):
        body = line.rstrip("\n")
        if not in_func:
            if FUNC_START_RE.match(body) and body.rstrip().endswith("{"):
                in_func = True
                body_lines = []
            out.append(line)
            continue
        if body == "}":
            emit(body_lines)
            out.append(line)
            in_func = False
            continue
        body_lines.append({"line": line, **_line_info(line)})
    return "".join(out)


def lead_end(text: str) -> int:
    """Byte offset just past the leading comment/blank/#include block."""
    pos = 0
    for line in text.splitlines(keepends=True):
        s = line.strip()
        if s.startswith("#include") or s.startswith("/*") or s.startswith("*") \
                or s.startswith("//") or s == "" or s.startswith("#pragma"):
            pos += len(line)
            # A block comment that has already ended on this line stops the run.
            if s.startswith("*/"):
                break
            continue
        break
    return pos


def twin_module(name: str, src: str, hdr: str, lazy: bool = False,
                suffix: str = "_ftz", variant: int = 1, extras: str = ""):
    prefix = name + "_"
    tprefix = name + suffix + "_"
    c = src.replace(prefix, tprefix)
    h = hdr.replace(prefix, tprefix)
    if suffix == "_approx":
        c = HELPER_RE.sub(lambda m: "spu_ap_" + m.group(1) + "(", c)
        pre = APPROX_PREAMBLE + extras
    elif lazy:
        c = rewrite_helpers(c)
        c = lazy_canonicalize(c)
        pre = FTZ_PREAMBLE_LAZY
    else:
        c = HELPER_RE.sub(lambda m: "spu_hw_" + m.group(1) + "(", c)
        pre = FTZ_PREAMBLE
    at = lead_end(c)
    c = c[:at] + pre + c[at:]
    if REG_LINE not in c:
        raise SystemExit(f"{name}: no register loop to convert")
    c = c.replace(REG_LINE,
                  "    if (!spu_register_function_var) return;   /* play tree: no variants */\n"
                  "    for (const spu_func_entry* e = spu_function_table; e->func; ++e)\n"
                  "        spu_register_function_var(e->addr, e->func, %d);" % variant)
    return c, h


def write_if_changed(path: str, text: str) -> bool:
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            if f.read() == text:
                return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return True


def add_extern(text: str, decl: str, anchor: str) -> str:
    """Add `decl` after a line containing `anchor` (once)."""
    if decl in text:
        return text
    out = []
    for line in text.splitlines(keepends=True):
        out.append(line)
        if anchor in line and "extern" in line:
            indent = line[:len(line) - len(line.lstrip())]
            out.append(f"{indent}{decl}\n")
    return "".join(out)


def patch_registration(path: str, twin_names, suffix: str = "_ftz") -> bool:
    """Call each twin module's register function next to its base one."""
    if not os.path.exists(path):
        return False
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    orig = text
    for name in twin_names:
        text = add_extern(text, f"extern void {name}{suffix}_spu_recomp_register(void);",
                          f"{name}_spu_recomp_register(void);")
        base = name + "_spu_recomp_register();"
        twin = name + suffix + "_spu_recomp_register();"
        if twin in text:
            continue
        # Insert the twin call after the line holding the base registration,
        # keeping the same image id (set by the spu_begin_image before it).
        out = []
        for line in text.splitlines(keepends=True):
            out.append(line)
            if base in line and "extern" not in line and not line.lstrip().startswith("*"):
                indent = line[:len(line) - len(line.lstrip())]
                if "spu_begin_image" in line:
                    # spu_begin_image(N); base_register(); -> keep image for twin
                    m = re.search(r"spu_begin_image\((\d+)\)", line)
                    out.append(f"{indent}spu_begin_image({m.group(1)}); {twin}\n")
                else:
                    out.append(f"{indent}{twin}\n")
        text = "".join(out)
    if text != orig:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        return True
    return False


def patch_workloads(path: str, twin_names, suffix: str = "_ftz") -> bool:
    """Add the twin entry registration (weak) to spu_workloads.c."""
    if not os.path.exists(path):
        return False
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    orig = text
    reg_img = "spu_workload_register_img" + suffix
    if reg_img not in text:
        marker = '#include "spu_workload.h"'
        what = "PS3RECOMP_SPU_FLOAT_APPROX" if suffix == "_approx" else "PS3RECOMP_SPU_FTZ"
        decl = (marker + "\n"
                "/* " + what + " twin entry (weak: the play runtime has no\n"
                " * variant registry and ignores it). */\n"
                "extern void " + reg_img + "(uint64_t, void (*)(spu_context*))\n"
                "    __attribute__((weak));\n")
        text = text.replace(marker, decl, 1)
    for name in twin_names:
        text = add_extern(text, f"extern void {name}{suffix}_spu_recomp_register(void);",
                          f"{name}_spu_recomp_register(void);")
        # The twin entry function has the same suffix as the base one.
        for line in text.splitlines():
            m = re.search(r"extern void (" + re.escape(name) + r"_spu_func_[0-9A-Fa-f]+)\(spu_context\*\);", line)
            if m:
                twin_fn = m.group(1).replace(name + "_spu_func_", name + suffix + "_spu_func_", 1)
                text = add_extern(text, f"extern void {twin_fn}(spu_context*);", m.group(1) + "(spu_context*);")
                break
    already_fp = set(re.findall(re.escape(reg_img) + r"\(\s*([^,]+),", text))
    for name in twin_names:
        base = name + "_spu_func_"
        twin = name + suffix + "_spu_func_"
        out = []
        pat = re.compile(r"spu_workload_register_img\(\s*([^,]+),\s*(" +
                         re.escape(base) + r"[0-9A-Fa-f]+)")
        regbase = name + "_spu_recomp_register();"
        regtwin = name + suffix + "_spu_recomp_register();"
        have_reg = regtwin in text
        for line in text.splitlines(keepends=True):
            out.append(line)
            if (not have_reg) and regbase in line and "extern" not in line:
                mreg = re.search(r"spu_begin_image\((\d+)\)", line)
                indent = line[:len(line) - len(line.lstrip())]
                if mreg:
                    out.append(f"{indent}spu_begin_image({mreg.group(1)}); {regtwin}\n")
                else:
                    out.append(f"{indent}{regtwin}\n")
                have_reg = True
            m = pat.search(line)
            if m and m.group(1).strip() not in already_fp:
                indent = line[:len(line) - len(line.lstrip())]
                entry = m.group(2).replace(base, twin, 1)
                fp = m.group(1).strip()
                already_fp.add(fp)
                out.append(f"{indent}if ({reg_img}) "
                           f"{reg_img}({fp}, {entry});\n")
        text = "".join(out)
    if text != orig:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        return True
    return False


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--spu-dir", default="recomp-work/spu_lifted")
    ap.add_argument("--remove", action="store_true",
                    help="Delete the generated twin directories instead.")
    ap.add_argument("--lazy-zero", action="store_true",
                    help="v4 experiment: keep float results raw and canonicalise "
                         "the sign of zero only where a value is observed (default off).")
    ap.add_argument("--approx", action="store_true",
                    help="write the variant-2 <name>_approx twins (not bit-exact, default off).")
    ap.add_argument("--fast-cfl", action="store_true",
                    help="with --approx: cflts/cfltu via scale + cvttps2dq (exact under FTZ|DAZ; default off).")
    ap.add_argument("--rcp-est", action="store_true",
                    help="with --approx: frest/frsqest via rcpps/rsqrtps (not exact; default off).")
    args = ap.parse_args()
    extras = (APPROX_FAST_CFL if args.fast_cfl else "") + (APPROX_RCP_EST if args.rcp_est else "")
    if extras and not args.approx:
        raise SystemExit("--fast-cfl/--rcp-est need --approx")
    suffix, variant = ("_approx", 2) if args.approx else ("_ftz", 1)

    root = args.spu_dir
    names = sorted(d for d in os.listdir(root)
                   if os.path.isfile(os.path.join(root, d, "spu_recomp.c")))
    if args.remove:
        for name in names:
            if not name.endswith(suffix):
                continue
            d = os.path.join(root, name)
            for f in os.listdir(d):
                os.remove(os.path.join(d, f))
            os.rmdir(d)
        print("removed twin directories")
        return 0

    base_names = [n for n in names if not n.endswith(("_ftz", "_approx"))]
    made = 0
    for name in base_names:
        d = os.path.join(root, name)
        with open(os.path.join(d, "spu_recomp.c"), "r", encoding="utf-8") as f:
            src = f.read()
        with open(os.path.join(d, "spu_recomp.h"), "r", encoding="utf-8") as f:
            hdr = f.read()
        c, h = twin_module(name, src, hdr, args.lazy_zero, suffix, variant, extras)
        tdir = os.path.join(root, name + suffix)
        if write_if_changed(os.path.join(tdir, "spu_recomp.c"), c):
            made += 1
        write_if_changed(os.path.join(tdir, "spu_recomp.h"), h)

    twins = [n for n in base_names if os.path.isdir(os.path.join(root, n + suffix))]
    for reg in ("jobmods_register.c", "jobmods_register_dxt.c"):
        if patch_registration(os.path.join(root, reg), twins, suffix):
            print(f"patched {reg}")
    if patch_workloads(os.path.join(root, "spu_workloads.c"), twins, suffix):
        print("patched spu_workloads.c")
    print(f"twins: {len(twins)} modules, {made} rewritten")
    return 0


if __name__ == "__main__":
    sys.exit(main())
