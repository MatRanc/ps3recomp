#!/usr/bin/env python3
"""Flatten the c690 screen-cull subtree (LS 0xD080 onward) into one C function.

The lifted 0x25/0x26 command handler calls 0xD080 as a subroutine.  From there
the cull is a pure tail-call state machine (SPU_DIRECT / SPU_RET only) that
ends by writing the kept-index list and returning through r0.  Flattening the
reachable blocks into one function removes the per-block GPR marshalling; the
SPU arithmetic and LS helpers are unchanged, so the result is bit-exact by
construction.

The subtree is game data and is not committed; generate the .inc after a lift:

    tools/c690_ref/gen_native_screen_stage.py \
        ../../recomp-work/spu_lifted/jobmod_c690c2f7b09a_eF5B8/spu_recomp.c \
        runtime/spu/c690_native_screen_stage.inc
"""
import re
import sys

PREFIX = "jobmod_c690c2f7b09a_eF5B8_spu_func_"
ROOT = "0000D080"
MAX_SR = 97          # highest register the subtree uses


def blocks(text):
    out = {}
    for m in re.finditer(r"^void (" + PREFIX + r"[0-9A-Fa-f]+(?:_body)?)\(spu_context\* ctx\) \{",
                         text, re.M):
        name = m.group(1)
        i = text.index("{", m.start())
        depth = 0
        j = i
        while j < len(text):
            c = text[j]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        out[name[len(PREFIX):].replace("_body", "")] = text[i + 1:j]
    return out


def reachable(body_by_addr):
    seen = set()
    todo = [ROOT]
    while todo:
        a = todo.pop()
        if a in seen or a not in body_by_addr:
            continue
        seen.add(a)
        for r in re.findall(PREFIX + r"([0-9A-Fa-f]+)", body_by_addr[a]):
            if r not in seen:
                todo.append(r)
    return seen


def transform(addr, body):
    # Per-block register loads disappear; sr0..sr97 stay live in the
    # flattened function.  The stores stay: they define the last value each
    # register had when a continuation would have reloaded it, including the
    # terminal writeback that a block which never stores a modified register
    # would otherwise leak into the caller.
    body = re.sub(r"spu_v4u sr\d+ = spu_u2v\(ctx->gpr\[\d+\]\);\s*", "", body)
    # Interrupt polls: the native stage runs to completion (same contract as
    # the native 0xFDA0 stage; the c690 job does not take SPU interrupts here).
    body = "\n".join(l for l in body.splitlines()
                     if "ctx->int_enable && (ctx->event_status & ctx->event_mask)" not in l)
    # Tail transfers become gotos.
    body = re.sub(r"SPU_DIRECT\(ctx,\s*0x[0-9A-Fa-f]+,\s*" + PREFIX +
                  r"([0-9A-Fa-f]+)\);", r"goto F_\1;", body)
    # Terminal returns (SPU_RET and the macro-free `return;`).
    body = body.replace("SPU_RET(ctx);", "goto L_DONE;")
    body = re.sub(r"\breturn;", "goto L_DONE;", body)
    # Block-local labels must not collide across the flattened bodies.
    for loc in set(re.findall(r"loc_([0-9A-Fa-f]+)", body)):
        body = body.replace("loc_" + loc, "loc_" + addr + "_" + loc)
    return body


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: gen_native_screen_stage.py <spu_recomp.c> <out.inc>")
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src).read()
    b = blocks(text)
    if ROOT not in b:
        raise SystemExit("no %s in %s" % (ROOT, src))
    have = reachable(b)
    have = sorted(have, key=lambda x: int(x, 16))

    lines = []
    lines.append("/* GENERATED by tools/c690_ref/gen_native_screen_stage.py from the")
    lines.append(" * c690 lifted module; DO NOT EDIT.  Flattened screen-cull subtree")
    lines.append(" * %s .. its return, no per-block GPR marshalling. */" % ROOT)
    lines.append("static void c690_native_screen_stage(spu_context* ctx) {")
    lines.append("    spu_v4u " + ", ".join("sr%d" % i for i in range(MAX_SR + 1)) + ";")
    for i in range(MAX_SR + 1):
        lines.append("    sr%d = spu_u2v(ctx->gpr[%d]);" % (i, i))
    lines.append("    goto F_%s;" % ROOT)
    for addr in have:
        lines.append("F_%s: ;" % addr)
        lines.append(transform(addr, b[addr]))
    lines.append("L_DONE: ;")
    lines.append("}")
    open(dst, "w").write("\n".join(lines) + "\n")
    print("wrote %s (%d blocks)" % (dst, len(have)))


if __name__ == "__main__":
    main()
