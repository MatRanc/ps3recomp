#!/usr/bin/env python3
# Generate the LS address -> lifted function table for the c690 job module.
import re, sys
src = sys.argv[1] if len(sys.argv) > 1 else \
    '/home/m/Documents/mlb16-online/recomp-work/spu_lifted/jobmod_c690c2f7b09a_eF5B8/spu_recomp.h'
out = sys.argv[2] if len(sys.argv) > 2 else 'reg_c690.c'
h = open(src).read()
fns = re.findall(r'void (jobmod_c690c2f7b09a_eF5B8_spu_func_([0-9A-F]{8}))\(spu_context\* ctx\);', h)
fns = sorted(set(fns), key=lambda x: int(x[1], 16))
with open(out, 'w') as f:
    f.write('/* generated by gen_reg_table.py from spu_recomp.h */\n')
    f.write('struct spu_context; typedef struct spu_context spu_context;\n')
    f.write('typedef void (*spu_fn)(spu_context*);\n')
    f.write('typedef struct { unsigned addr; spu_fn fn; } reg_ent;\n')
    for name, addr in fns: f.write('void %s(spu_context*);\n' % name)
    f.write('const reg_ent g_c690_reg[] = {\n')
    for name, addr in fns: f.write('  {0x%s, %s},\n' % (addr, name))
    f.write('};\nconst int g_c690_reg_n = (int)(sizeof(g_c690_reg)/sizeof(g_c690_reg[0]));\n')
print('wrote %s (%d functions)' % (out, len(fns)))
