#!/usr/bin/env python3
"""Flatten the c690 0xFDA0 reference state machine into one C function.

The reference keeps the lifted per-continuation calling convention: every
block reloads the SPU GPRs it uses from ctx->gpr and stores them back before
a tail call. The flattened kernel keeps sr0..sr93 live in locals for the whole
traversal and turns continuation calls into gotos, which removes tens of KiB
of GPR marshalling per stage call. SPU arithmetic/LS helpers are unchanged, so
the result is bit-exact by construction.
"""
import re
import sys

PREFIX = "jobmod_c690c2f7b09a_eF5B8_spu_func_"

def blocks(text):
    out = []
    for m in re.finditer(r"^void (" + PREFIX + r"[0-9A-Fa-f]+(?:_body)?)\(spu_context\* ctx\) \{", text, re.M):
        name = m.group(1)
        i = text.index("{", m.start())
        depth = 0
        j = i
        while j < len(text):
            c = text[j]
            if c == "{": depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0: break
            j += 1
        out.append((name, text[i+1:j]))
    return out

def transform(name, body):
    fid = name[len(PREFIX):].replace("_body", "")
    body = re.sub(r"spu_v4u sr\d+ = spu_u2v\(ctx->gpr\[\d+\]\);", "", body)
    body = re.sub(r"sr\d+ = spu_u2v\(ctx->gpr\[\d+\]\);", "", body)
    body = re.sub(r"ctx->gpr\[\d+\] = spu_v2u\(sr\d+\);", "", body)
    body = re.sub(r"ctx->gpr\[0\] = spu_link\((0x[0-9A-Fa-f]+)\);\s*",
                  r"sr0 = spu_u2v(spu_link(\1)); ", body)
    body = re.sub(r"return " + PREFIX + r"([0-9A-Fa-f]+)(?:_body)?\(ctx\);", r"goto F_\1;", body)
    body = re.sub(PREFIX + r"([0-9A-Fa-f]+)(?:_body)?\(ctx\);", r"goto F_\1;", body)
    body = re.sub(r"\breturn;", "goto L_DONE;", body)
    locs = set(re.findall(r"loc_([0-9A-Fa-f]+)", body))
    for loc in locs:
        body = body.replace("loc_" + loc, "loc_" + fid + "_" + loc)
    return body

def main():
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src).read()
    bs = blocks(text)
    names = {n for n, _ in bs}
    have = {n: transform(n, b) for n, b in bs}
    lines = []
    lines.append("/* GENERATED by tools/c690_ref/gen_native_stage.py from ref_c690_stage.c. */")
    lines.append("/* Bit-exact flattened 0xFDA0 stage: no per-block GPR marshalling. */")
    lines.append('#include <stdint.h>')
    lines.append('#include <stdio.h>')
    lines.append('#include <stdlib.h>')
    lines.append('#include <string.h>')
    lines.append('#include "spu_context.h"')
    lines.append('#include "spu_helpers.h"')
    lines.append("")
    lines.append("void c690_native_stage(spu_context* ctx) {")
    lines.append("    spu_v4u " + ", ".join("sr%d" % i for i in range(94)) + ";")
    for i in range(94):
        lines.append("    sr%d = spu_u2v(ctx->gpr[%d]);" % (i, i))
    lines.append("    goto F_0000FDA0;")
    for name, _ in bs:
        fid = name[len(PREFIX):].replace("_body", "")
        lines.append("F_%s: ;" % fid)
        lines.append(have[name])
    lines.append("L_DONE: ;")
    for i in range(1, 94):
        lines.append("    ctx->gpr[%d] = spu_v2u(sr%d);" % (i, i))
    lines.append("}")
    open(dst, "w").write("\n".join(lines) + "\n")
    print("wrote", dst, "blocks", len(bs))

if __name__ == "__main__":
    main()
