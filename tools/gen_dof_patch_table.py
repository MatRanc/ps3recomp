#!/usr/bin/env python3
"""Generate libs/video/rsx_dof_patch_table.h from the title's EBOOT and the
"Better depth of field" patch.

The patch itself is authored in another project (mlb16-revival-server,
tools/dof_patch.py + patches/MLB16_dof_fix.yml); this tool only turns its
.be64 write list into a compact C table and records fingerprints of the
original fragment programs the patch was generated from, so the runtime can
refuse to apply it to a different EBOOT.

usage: python3 tools/gen_dof_patch_table.py EBOOT.elf MLB16_dof_fix.yml \
           -o libs/video/rsx_dof_patch_table.h

Verification regions are the two program headers plus their 0x340-byte
original ucode, hashed with FNV-1a 64. They are checked against guest memory
after ELF load, before anything is written.
"""
import argparse
import os
import re
import struct
import sys

FNV_OFFSET = 14695981039346656037
FNV_PRIME = 1099511628211

# The two SET_SHADER_PROGRAM headers dof_patch.py rewrites. The code goes past
# the end of the last LOAD segment, so it has no file-backed original.
HEADERS = (0x1121cc0, 0x1122080)
HEADER_SIZE = 0x80
PROGRAM_SIZE = 0x340
VERIFY_LEN = HEADER_SIZE + PROGRAM_SIZE


def fnv1a64(data):
    h = FNV_OFFSET
    for b in data:
        h = ((h ^ b) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return h


def load_segments(eboot):
    if len(eboot) < 64 or eboot[:4] != b"\x7fELF" or eboot[4] != 2 or eboot[5] != 2:
        raise SystemExit("not a 64-bit big-endian ELF")
    phoff, = struct.unpack_from(">Q", eboot, 0x20)
    phentsize, phnum = struct.unpack_from(">HH", eboot, 0x36)
    segs = []
    for i in range(phnum):
        p_type, _, off, vaddr, _, filesz, memsz, _ = struct.unpack_from(
            ">IIQQQQQQ", eboot, phoff + i * phentsize)
        if p_type == 1 and memsz:
            segs.append((vaddr, memsz, off, filesz))
    return segs


def read_va(eboot, segs, va, n):
    for vaddr, _, off, filesz in segs:
        if vaddr <= va and va + n <= vaddr + filesz:
            start = off + va - vaddr
            return eboot[start:start + n]
    raise SystemExit("0x%X+0x%X is not file-backed" % (va, n))


def parse_writes(path):
    writes = []
    rx = re.compile(r"\[\s*be64\s*,\s*0x([0-9a-fA-F]+)\s*,\s*0x([0-9a-fA-F]+)\s*\]")
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            m = rx.search(line)
            if not m:
                continue
            addr = int(m.group(1), 16)
            data = int(m.group(2), 16).to_bytes(8, "big")
            writes.append((addr, data))
    if not writes:
        raise SystemExit("no be64 writes found in %s" % path)
    return writes


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("eboot")
    ap.add_argument("patch")
    ap.add_argument("-o", "--out", required=True)
    args = ap.parse_args()

    eboot = open(args.eboot, "rb").read()
    segs = load_segments(eboot)
    writes = parse_writes(args.patch)

    originals = []
    for hdr in HEADERS:
        region = read_va(eboot, segs, hdr, VERIFY_LEN)
        originals.append((hdr, VERIFY_LEN, fnv1a64(region)))
    prog0 = read_va(eboot, segs, HEADERS[0] + HEADER_SIZE, PROGRAM_SIZE)
    prog1 = read_va(eboot, segs, HEADERS[1] + HEADER_SIZE, PROGRAM_SIZE)
    if prog0 != prog1:
        raise SystemExit("the two depth-of-field programs differ; refusing to generate")

    # The new code is one contiguous run past the file end. Collect it so the
    # runtime can check that the target really is unused before writing.
    code_addrs = sorted(a for a, _ in writes if a < HEADERS[0])
    if not code_addrs:
        raise SystemExit("no code writes below the headers")
    code_addr = code_addrs[0]
    code_end = code_addr + 8
    for a in code_addrs[1:]:
        if a != code_end:
            raise SystemExit("code writes are not contiguous at 0x%X" % a)
        code_end = a + 8
    for a, data in writes:
        if a >= code_addr and a < code_end and a % 8:
            raise SystemExit("unaligned code write at 0x%X" % a)

    # Replay the header writes on the original bytes and prove both headers
    # name the patched program before generating anything the runtime trusts.
    for hdr in HEADERS:
        head = bytearray(read_va(eboot, segs, hdr, HEADER_SIZE))
        for a, data in writes:
            if hdr <= a and a + 8 <= hdr + HEADER_SIZE:
                head[a - hdr:a - hdr + 8] = data
        size, = struct.unpack_from(">I", head, 0)
        off, = struct.unpack_from(">i", head, 0x10)
        if size != code_end - code_addr:
            raise SystemExit("header 0x%X size 0x%X does not cover the code" % (hdr, size))
        if (hdr + off) & 0xFFFFFFFF != code_addr:
            raise SystemExit("header 0x%X offset does not point at 0x%X" % (hdr, code_addr))

    out = []
    out.append("/* Generated by tools/gen_dof_patch_table.py. Do not edit.\n")
    out.append(" * Patch: %s\n" % os.path.basename(args.patch))
    out.append(" * EBOOT: %s\n" % os.path.basename(args.eboot))
    out.append(" */\n")
    out.append("#ifndef RSX_DOF_PATCH_TABLE_H\n#define RSX_DOF_PATCH_TABLE_H\n")
    out.append("#include <stdint.h>\n\n")
    out.append("#define RSX_DOF_PATCH_CODE_ADDR 0x%08xu\n" % code_addr)
    out.append("#define RSX_DOF_PATCH_CODE_SIZE 0x%08xu\n" % (code_end - code_addr))
    out.append("#define RSX_DOF_PATCH_HEADER_SIZE 0x%xu\n" % HEADER_SIZE)
    out.append("#define RSX_DOF_PATCH_PROGRAM_SIZE 0x%xu\n\n" % PROGRAM_SIZE)
    out.append("typedef struct rsx_dof_patch_write {\n")
    out.append("    uint32_t addr;\n    uint8_t bytes[8];\n} rsx_dof_patch_write;\n\n")
    out.append("static const rsx_dof_patch_write g_rsx_dof_patch_writes[] = {\n")
    for a, data in writes:
        out.append("    { 0x%08xu, { %s } },\n" % (a, ", ".join("0x%02x" % b for b in data)))
    out.append("};\n")
    out.append("#define RSX_DOF_PATCH_NUM_WRITES %uu\n\n" % len(writes))
    out.append("typedef struct rsx_dof_verify_region {\n")
    out.append("    uint32_t addr;\n    uint32_t len;\n    uint64_t fnv1a64;\n} rsx_dof_verify_region;\n\n")
    out.append("static const rsx_dof_verify_region g_rsx_dof_verify_regions[] = {\n")
    for a, n, h in originals:
        out.append("    { 0x%08xu, 0x%xu, 0x%016xull },\n" % (a, n, h))
    out.append("};\n")
    out.append("#define RSX_DOF_VERIFY_REGION_COUNT %uu\n\n" % len(originals))
    out.append("#endif /* RSX_DOF_PATCH_TABLE_H */\n")

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("".join(out))
    print("wrote %s: %u writes, code 0x%X+0x%X, %u verify regions" %
          (args.out, len(writes), code_addr, code_end - code_addr, len(originals)))


if __name__ == "__main__":
    main()
